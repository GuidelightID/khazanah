import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import {
  FIXTURE_PAGE_COUNT,
  fixtureCatalog,
  fixturePages,
  type PageManifest,
} from '@guidelightid/mushaf-core';
import { sha256Hex } from './hash.js';

export interface PullResult {
  outDir: string;
  pagesWritten: number;
  manifestPath: string;
  noticePath: string;
}

/**
 * Materialize MIT fixture IR into a host `public/mushaf`-style directory.
 */
export async function pullFixtureSource(outDir: string): Promise<PullResult> {
  const pagesDir = path.join(outDir, 'pages');
  await mkdir(pagesDir, { recursive: true });

  const entries: PageManifest['pages'] = [];
  const verseIndex: Record<string, number> = {};

  for (let page = 1; page <= FIXTURE_PAGE_COUNT; page++) {
    const ir = fixturePages[page];
    if (!ir) continue;
    const fileName = `${String(page).padStart(4, '0')}.json`;
    const relPath = `pages/${fileName}`;
    const abs = path.join(outDir, relPath);
    const body = `${JSON.stringify(ir, null, 2)}\n`;
    await writeFile(abs, body, 'utf8');
    const buf = Buffer.from(body, 'utf8');
    entries.push({
      page,
      path: relPath,
      bytes: buf.byteLength,
      sha256: sha256Hex(buf),
    });
    for (const verse of ir.verses) {
      verseIndex[verse.verseKey] = page;
    }
  }

  const manifest: PageManifest = {
    version: 1,
    mushaf: 'fixture',
    baseUrl: '.',
    pages: entries,
    fontModel: 'unicode_bbox',
    generatedAt: new Date().toISOString(),
  };

  const manifestPath = path.join(outDir, 'pages.manifest.json');
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');

  const catalogPath = path.join(outDir, 'catalog.json');
  await writeFile(catalogPath, `${JSON.stringify(fixtureCatalog, null, 2)}\n`, 'utf8');

  const verseIndexPath = path.join(outDir, 'verse-index.json');
  await writeFile(verseIndexPath, `${JSON.stringify(verseIndex, null, 2)}\n`, 'utf8');

  const licensesPath = path.join(outDir, 'licenses.json');
  await writeFile(
    licensesPath,
    `${JSON.stringify(
      [
        {
          spdx: 'MIT',
          name: 'MIT',
          allowsNpmRedistribution: true,
          allowsModification: true,
          notes: 'Synthetic fixture IR generated by @guidelightid/mushaf-cli',
        },
      ],
      null,
      2,
    )}\n`,
    'utf8',
  );

  const noticePath = path.join(outDir, 'NOTICE');
  await writeFile(
    noticePath,
    `Mushaf data pull — source: fixture
Generated: ${new Date().toISOString()}

These page IR files are synthetic fixtures under the MIT license.
They are NOT a reproduction of the printed Madinah Mushaf.

For production Madinah geometry/fonts, use an approved source in
LICENSES/matrix.md and a non-MIT redistribution path.
`,
    'utf8',
  );

  return {
    outDir,
    pagesWritten: entries.length,
    manifestPath,
    noticePath,
  };
}
